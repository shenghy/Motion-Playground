export function getMotionDefinition(id: MotionId) {
  return motionRegistry.find((motion) => motion.id === id) ?? motionRegistry[0]
}

export function isFullscreenMotion(id: MotionId) {
  return getMotionDefinition(id).scope === 'fullscreen'
}

export const fullscreenMotionRegistry = motionRegistry.filter(
  (motion) => motion.scope === 'fullscreen',
)

export function resolveMotionRenderer(id: MotionId) {
  return getMotionDefinition(id).canvasRenderer
}

export function resolveMotionBounds(id: MotionId) {
  return getMotionDefinition(id).canvasBounds
}
